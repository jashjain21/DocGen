from src.engine import TemplateRenderer
from src.schema import Customer, LineItem, Invoice
from src.exceptions import TemplateError
import pytest


def test_template_renderer_creation():
    renderer = TemplateRenderer()
    assert renderer.template_dir == "src/templates"
    assert renderer.env is not None


def test_render_html_success():
    renderer = TemplateRenderer()
    customer = Customer(name="Jane Doe", address="456 Elm St\nCity, State 12345")
    line_items = [
        LineItem(description="Item 1", quantity=1, unit_price=20.00),
        LineItem(description="Item 2", quantity=2, unit_price=15.50)
    ]
    invoice = Invoice(
        invoice_number="INV-002",
        date="2023-10-02",
        customer=customer,
        line_items=line_items
    )

    html = renderer.render_html("invoice.html", invoice)

    # Check basic structure
    assert "<!DOCTYPE html>" in html
    assert "Jane Doe" in html
    assert "INV-002" in html
    assert "$20.00" in html  # formatted currency
    assert "$51.00" in html  # total
    assert "Generated by DocGen on" in html  # timestamp injected
    assert "<br>" in html  # address formatting


def test_render_html_template_error():
    renderer = TemplateRenderer()
    # Create a minimal invoice
    customer = Customer(name="Test", address="Test Addr")
    invoice = Invoice(
        invoice_number="TEST",
        date="2023-01-01",
        customer=customer,
        line_items=[]
    )

    # This should raise because 'nonexistent.html' doesn't exist
    with pytest.raises(TemplateError, match="Template rendering error"):
        renderer.render_html("nonexistent.html", invoice)


